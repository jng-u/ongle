package kr.ongyeol.journal;

/** Installed only into the app's top-level document, before transferring its private port. */
final class ShellScript {
    static final String INSTALL = String.join("\n",
        "(() => {",
        "if (window !== window.top || window.__ongleShellInstalled) return;",
        "window.__ongleShellInstalled = true;",
        "let port, reply, busy = false, sequence = 0, queue = Promise.resolve(), broken = false; const blobs = new Map();",
        "const ready = new Promise(resolve => {",
        "  window.addEventListener('message', function receive(e) {",
        "    if (e.source !== null || e.data !== '__PORT_TOKEN__' || !e.ports[0]) return;",
        "    window.removeEventListener('message', receive); port = e.ports[0];",
        "    port.onmessage = e => { if (reply) reply(e.data); };",
        "    port.start(); resolve();",
        "  });",
        "});",
        "function send(value) {",
        "  const task = queue.then(async () => {",
        "    await ready; if (broken) throw Error('앱을 다시 열어 주세요.');",
        "    return new Promise((resolve, reject) => {",
        "      const requestId = ++sequence;",
        "      const timer = value.op === 'save' ? null : setTimeout(() => { reply = null; broken = true; reject(Error('기기 연결 시간이 초과됐어요. 앱을 다시 열어 주세요.')); }, value.op === 'alarms.requestPermission' ? 180000 : 10000);",
        "      reply = raw => {",
        "        let data; try { data = JSON.parse(raw); } catch { return; }",
        "        if (data.requestId !== requestId) return;",
        "        clearTimeout(timer); reply = null;",
        "        data.ok ? resolve(data.value) : reject(Error('기기 요청을 처리하지 못했어요.'));",
        "      };",
        "      try { port.postMessage(JSON.stringify({...value, requestId})); }",
        "      catch (e) { clearTimeout(timer); reply = null; reject(e); }",
        "    });",
        "  });",
        "  queue = task.catch(() => {}); return task;",
        "}",
        "function gesture(op) {",
        "  if (!navigator.userActivation || !navigator.userActivation.isActive) return Promise.reject(Error('버튼을 눌러 권한을 설정해 주세요.'));",
        "  return send({op});",
        "}",
        "window.ongyeolAlarms = Object.freeze({",
        "  status: () => send({op:'alarms.status'}),",
        "  requestPermission: () => gesture('alarms.requestPermission'),",
        "  requestExact: () => gesture('alarms.requestExact'),",
        "  sync: payload => send({op:'alarms.sync', payload})",
        "});",
        "function refreshAlarms() {",
        "  if (!document.hidden) window.ongyeolAlarms.status().then(status => window.dispatchEvent(new CustomEvent('ongyeol-alarms-status', {detail:status}))).catch(() => {});",
        "}",
        "document.addEventListener('visibilitychange', refreshAlarms);",
        "window.addEventListener('focus', refreshAlarms);",
        "window.addEventListener('ongyeol-alarms-resume', refreshAlarms);",
        "ready.then(() => { window.dispatchEvent(new Event('ongyeol-alarms-ready')); refreshAlarms(); });",
        "const create = URL.createObjectURL.bind(URL), revoke = URL.revokeObjectURL.bind(URL);",
        "URL.createObjectURL = blob => { const url = create(blob); blobs.set(url, blob); return url; };",
        "URL.revokeObjectURL = url => { blobs.delete(url); revoke(url); };",
        "async function saveBlob(blob, name) {",
        "  if (busy) return {status:'failed'};",
        "  busy = true;",
        "  try {",
        "    if (!blob.size || blob.size > 8388608) throw Error('파일 크기를 확인해 주세요 (최대 8MB).');",
        "    await send({op:'begin', name, mime:blob.type.split(';')[0], size:blob.size});",
        "    const bytes = new Uint8Array(await blob.arrayBuffer());",
        "    for (let i = 0; i < bytes.length; i += 32768) {",
        "      const chunk = bytes.subarray(i, i + 32768); let binary = '';",
        "      for (const byte of chunk) binary += String.fromCharCode(byte);",
        "      await send({op:'chunk', data:btoa(binary)});",
        "    }",
        "    return await send({op:'save'});",
        "  } catch (e) { return {status:'failed'}; } finally { busy = false; }",
        "}",
        "window.ongyeolFiles = Object.freeze({save:saveBlob});",
        "async function save(anchor) {",
        "  const blob = blobs.get(anchor.href);",
        "  const result = blob ? await saveBlob(blob, anchor.download) : {status:'failed'};",
        "  alert(result.status === 'saved' ? '파일을 저장했어요.' : result.status === 'cancelled' ? '파일 저장을 취소했어요.' : '파일을 저장하지 못했어요.');",
        "}",
        "function downloadable(a) { return a && a.hasAttribute('download') && a.href.startsWith('blob:' + location.origin + '/'); }",
        "const click = HTMLAnchorElement.prototype.click;",
        "HTMLAnchorElement.prototype.click = function() { if (downloadable(this)) { void save(this); return; } return click.call(this); };",
        "document.addEventListener('click', e => {",
        "  const a = e.target.closest && e.target.closest('a');",
        "  if (downloadable(a)) { e.preventDefault(); e.stopImmediatePropagation(); void save(a); }",
        "}, true);",
        "window.print = () => { if (!busy) { busy = true; send({op:'print'}).catch(e => alert(e.message)).finally(() => { busy = false; }); } };",
        "})();"
    );
    private ShellScript() { }
}
